const assert = require('node:assert/strict')
const {installBrowser, libPath} = require('./ts-harness.cjs')
const b=installBrowser()
const {DAY_MARKS_KEY,localDayKey,readMarks,toggleDayMark}=require(libPath('daymarks.ts'))
const before=new Date(2026,9,24,23,59)
const after=new Date(2026,9,25,0,1)
toggleDayMark('yesterday1',before);toggleDayMark('yesterday2',before)
toggleDayMark('today1',after)
assert.deepEqual(readMarks()[localDayKey(after)],['today1'])
assert.deepEqual(readMarks()[localDayKey(before)],['yesterday1','yesterday2'])
toggleDayMark('today1',after)
assert.deepEqual(readMarks()[localDayKey(after)],[])
