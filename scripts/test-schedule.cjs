const assert = require('node:assert/strict')
const {libPath} = require('./ts-harness.cjs')
const {normalizeSchedule, dueSlot} = require(libPath('schedule.ts'))
assert.deepEqual(normalizeSchedule(['21:00','08:00','08:00','25:00','x',5]), ['08:00','21:00'])
assert.deepEqual(normalizeSchedule(null), [])
const at=(h,m)=>new Date(2026,9,28,h,m)
assert.equal(dueSlot(['08:00'], at(7,59)), null)
assert.equal(dueSlot(['08:00'], at(8,0)), '08:00')
assert.equal(dueSlot(['08:00'], at(9,59)), '08:00')
assert.equal(dueSlot(['08:00'], at(10,0)), null)
assert.equal(dueSlot(['08:00','09:00'], at(9,30)), '09:00')
assert.equal(dueSlot([], at(9,30)), null)
